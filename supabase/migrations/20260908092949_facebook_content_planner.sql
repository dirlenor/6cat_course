create table public.content_posts (
  id uuid primary key default gen_random_uuid(),
  week_start date not null,
  planned_date date not null,
  slot_number smallint not null check (slot_number between 1 and 2),
  scheduled_at timestamptz not null,
  title text not null check (char_length(trim(title)) between 1 and 180),
  content_type text not null default 'education'
    check (content_type in ('education', 'inspiration', 'behind_the_scenes', 'promotion', 'engagement')),
  objective text not null default '' check (char_length(objective) <= 1000),
  caption text not null default '' check (char_length(caption) <= 12000),
  cta text not null default '' check (char_length(cta) <= 1000),
  image_brief text not null default '' check (char_length(image_brief) <= 4000),
  image_prompt text not null default '' check (char_length(image_prompt) <= 8000),
  image_path text check (image_path is null or (char_length(image_path) between 1 and 500 and image_path !~ '\\.\\.')),
  image_required boolean not null default false,
  source text not null default 'manual' check (source in ('manual', 'ai')),
  status text not null default 'draft'
    check (status in ('draft', 'scheduled', 'publishing', 'published', 'failed')),
  revision integer not null default 1 check (revision > 0),
  approved_at timestamptz,
  approved_by uuid references auth.users(id) on delete set null,
  published_at timestamptz,
  external_post_id text,
  external_post_url text check (external_post_url is null or external_post_url ~ '^https://([A-Za-z0-9-]+\.)*facebook\.com/'),
  publish_attempts smallint not null default 0 check (publish_attempts between 0 and 100),
  last_error text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (planned_date, slot_number),
  check (week_start = planned_date - ((extract(isodow from planned_date)::integer - 1) * interval '1 day')),
  check (
    (status in ('scheduled', 'publishing', 'published', 'failed') and approved_at is not null)
    or status = 'draft'
  )
);

create index content_posts_week_idx
