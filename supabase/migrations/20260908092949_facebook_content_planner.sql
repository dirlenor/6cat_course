create or replace function private.guard_content_post_update()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  publishable_fields_changed boolean :=
    new.planned_date is distinct from old.planned_date
    or new.scheduled_at is distinct from old.scheduled_at
    or new.title is distinct from old.title
    or new.content_type is distinct from old.content_type
    or new.objective is distinct from old.objective
    or new.caption is distinct from old.caption
    or new.cta is distinct from old.cta
    or new.image_brief is distinct from old.image_brief
    or new.image_prompt is distinct from old.image_prompt
    or new.image_path is distinct from old.image_path
    or new.image_required is distinct from old.image_required;
begin
  if old.status = 'published' then
    raise exception 'โพสต์ที่เผยแพร่แล้วแก้ไขไม่ได้';
  end if;

  if old.status = 'publishing' and publishable_fields_changed then
    raise exception 'โพสต์กำลังถูกเผยแพร่ กรุณารอหรือตรวจสอบสถานะก่อนแก้ไข';
  end if;

  if publishable_fields_changed then
    new.status := 'draft';
    new.approved_at := null;
    new.approved_by := null;
    new.last_error := null;
  end if;

  new.revision := old.revision + 1;
  new.updated_at := now();
  return new;
end;
$$;

create trigger guard_content_post_update
before update on public.content_posts
for each row execute function private.guard_content_post_update();

create or replace function public.reconcile_content_post(
  p_post_id uuid,
  p_revision integer,
  p_published boolean,
  p_external_post_url text default null
)
returns setof public.content_posts
language plpgsql
security invoker
set search_path = ''
as $$
declare
  affected integer;
begin
  if coalesce(auth.jwt() ->> 'email', '') <> 'admin@6cat.com' then
    raise exception 'ไม่มีสิทธิ์จัดการคอนเทนต์';
  end if;
  if p_external_post_url is not null and p_external_post_url !~ '^https://([A-Za-z0-9-]+\.)*facebook\.com/' then
    raise exception 'ลิงก์โพสต์ Facebook ไม่ถูกต้อง';
  end if;

  return query
  update public.content_posts
  set
    status = case when p_published then 'published' else 'draft' end,
    approved_at = case when p_published then approved_at else null end,
    approved_by = case when p_published then approved_by else null end,
    published_at = case when p_published then now() else null end,
    external_post_url = case when p_published then p_external_post_url else null end,
    last_error = null
  where id = p_post_id
    and status = 'publishing'
    and revision = p_revision
    and updated_at <= now() - interval '5 minutes'
  returning *;

  get diagnostics affected = row_count;
  if affected <> 1 then
    raise exception 'โพสต์ยังทำงานอยู่ หรือสถานะถูกเปลี่ยนจากหน้าจออื่นแล้ว กรุณาโหลดใหม่';
  end if;
end;
$$;

revoke all on function public.reconcile_content_post(uuid, integer, boolean, text) from public, anon;
grant execute on function public.reconcile_content_post(uuid, integer, boolean, text) to authenticated;

